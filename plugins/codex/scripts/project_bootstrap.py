#!/usr/bin/env python3
"""Plan or apply the project-scoped Synaptory Codex agent bootstrap."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path
from typing import Any

try:  # Python 3.11+
    import tomllib as _toml
except ModuleNotFoundError:  # Python 3.9/3.10 test and supported bootstrap path
    vendor = Path(__file__).resolve().parent / "_vendor"
    if str(vendor) not in sys.path:
        sys.path.insert(0, str(vendor))
    try:
        import synaptory_tomli as _toml  # type: ignore[no-redef]
    except ModuleNotFoundError:
        _toml = None  # type: ignore[assignment]

OWNERSHIP_HEADER = (
    "# GENERATED by Synaptory Codex bootstrap — managed file; do not hand-edit."
)
CONFIG_OWNERSHIP_HEADER = (
    "# GENERATED by Synaptory Codex bootstrap — managed file; preserve multi_agent_v2."
)
AGENTS_START = "<!-- synaptory:codex:start -->"
AGENTS_END = "<!-- synaptory:codex:end -->"
ALL_ROLES = (
    "code-reviewer",
    "compliance-engineer",
    "platform-engineer",
    "project-owner",
    "quality-engineer",
    "research-advisor",
    "software-engineer",
    "solution-architect",
    "technical-writer",
)
MANAGED_ROLES = ALL_ROLES


def _plugin_root() -> Path:
    return Path(__file__).resolve().parent.parent


def _template_path(role: str) -> Path:
    if role not in ALL_ROLES:
        raise ValueError(f"unsupported Synaptory role: {role}")
    return _plugin_root() / "assets" / "agent-templates" / f"{role}.toml"


def _read_template(role: str) -> str:
    path = _template_path(role)
    text = path.read_text(encoding="utf-8")
    if not text.startswith(OWNERSHIP_HEADER + "\n"):
        raise ValueError(f"agent template lacks ownership header: {path.name}")
    required = {"name", "description", "developer_instructions"}
    assignments = re.findall(r"(?m)^([A-Za-z_][A-Za-z0-9_]*)\s*=", text)
    if set(assignments) != required or len(assignments) != len(required):
        raise ValueError(f"agent template has unsupported fields: {path.name}")
    name_match = re.search(r'(?m)^name\s*=\s*"([^"\n]+)"\s*$', text)
    description_match = re.search(
        r'(?m)^description\s*=\s*"([^"\n]+)"\s*$', text
    )
    instructions_match = re.search(
        r'(?ms)^developer_instructions\s*=\s*"""\n(.+?)\n"""\s*\Z', text
    )
    payload = {
        "name": name_match.group(1) if name_match else "",
        "description": description_match.group(1) if description_match else "",
        "developer_instructions": (
            instructions_match.group(1) if instructions_match else ""
        ),
    }
    expected_name = f"synaptory-{role}"
    if payload.get("name") != expected_name:
        raise ValueError(f"agent template name must be {expected_name}: {path.name}")
    if not all(
        isinstance(payload[key], str) and payload[key].strip() for key in required
    ):
        raise ValueError(
            f"agent template fields must be non-empty strings: {path.name}"
        )
    return text if text.endswith("\n") else text + "\n"


def _agents_block() -> str:
    role_list = ", ".join(f"`synaptory-{role}`" for role in MANAGED_ROLES)
    return (
        f"{AGENTS_START}\n"
        "## Synaptory Codex runtime (managed)\n\n"
        "Use `$synaptory` for Synaptory delivery work in this repository. "
        "Do not start a structured sprint or story run unless the Synaptory "
        "doctor reports `structured_execution_ready: true`.\n\n"
        f"When the governed runtime authorizes delegation, use only the managed "
        f"profiles {role_list}, and include the complete Synaptory execution "
        "envelope in every dispatch. Spawn a named managed profile with no "
        "inherited conversation history; never combine a custom profile with "
        "a full-history fork, and wait only on a successful spawn's concrete "
        "agent identifier. Never edit "
        "`.synaptory/.orchestrator/pipeline-state.json` directly; all state and "
        "receipt changes must pass through governed Synaptory MCP operations.\n\n"
        "Project custom-agent changes are discovered in a new Codex task.\n"
        f"{AGENTS_END}"
    )


def _multi_agent_v2_value(text: str) -> bool | None:
    """Read the semantic TOML value, including dotted/quoted/inline forms."""

    payload = _parse_toml(text)
    features = payload.get("features")
    if features is None:
        return None
    if not isinstance(features, dict):
        raise ValueError("features must be a TOML table")
    value = features.get("multi_agent_v2")
    if value is None:
        return None
    if not isinstance(value, bool):
        raise ValueError("features.multi_agent_v2 must be a boolean")
    return value


def _parse_toml(text: str) -> dict[str, Any]:
    if _toml is None:
        raise ValueError(
            "the bundled Python 3.9 TOML parser is unavailable"
        )
    try:
        payload = _toml.loads(text)
    except Exception as exc:
        raise ValueError(f"Codex config is not valid TOML: {exc}") from exc
    if not isinstance(payload, dict):
        raise ValueError("Codex config must contain a TOML document")
    return payload


def _features_table_index(lines: list[str]) -> int | None:
    """Find a semantically equivalent ``[features]`` table header."""

    probe = "__synaptory_feature_probe__"
    for index, raw in enumerate(lines):
        candidate = raw.strip()
        if not candidate.startswith("["):
            continue
        try:
            payload = _parse_toml(f"{candidate}\n{probe} = true\n")
        except ValueError:
            continue
        features = payload.get("features")
        if (
            isinstance(features, dict)
            and features.get(probe) is True
            and set(features) == {probe}
            and set(payload) == {"features"}
        ):
            return index
    return None


def _validated_config(text: str) -> str:
    payload = _parse_toml(text)
    features = payload.get("features")
    if not isinstance(features, dict) or features.get("multi_agent_v2") is not True:
        raise ValueError("rendered config did not enable features.multi_agent_v2")
    return text


def _codex_config(existing: str | None) -> tuple[str, str]:
    """Return desired config content and its plan status.

    A missing config is managed wholly by Synaptory. Existing user config is
    preserved byte-for-byte except for one additive feature line or block.
    An explicit user `false` is a conflict and is never overwritten.
    """

    managed = f"{CONFIG_OWNERSHIP_HEADER}\n[features]\nmulti_agent_v2 = true\n"
    if existing is None:
        return _validated_config(managed), "create"
    value = _multi_agent_v2_value(existing)
    if value is True:
        return existing, "unchanged"
    if value is False:
        return existing, "conflict"
    payload = _parse_toml(existing)
    lines = existing.splitlines(keepends=True)
    features_index = _features_table_index(lines)
    if isinstance(payload.get("features"), dict) and features_index is None:
        raise ValueError(
            "features is defined with dotted keys or an inline table; add "
            "features.multi_agent_v2 = true explicitly before bootstrap"
        )
    if features_index is not None:
        insertion = "# synaptory: required for named fresh-agent dispatch\nmulti_agent_v2 = true\n"
        lines.insert(features_index + 1, insertion)
        return _validated_config("".join(lines)), "update"
    separator = "" if not existing or existing.endswith("\n\n") else ("\n" if existing.endswith("\n") else "\n\n")
    addition = (
        "# synaptory:codex:features:start\n"
        "[features]\n"
        "multi_agent_v2 = true\n"
        "# synaptory:codex:features:end\n"
    )
    return _validated_config(existing + separator + addition), "update"


def _project_path(project_dir: str | os.PathLike[str] | Path) -> Path:
    project = Path(project_dir).expanduser().resolve()
    if not project.is_dir():
        raise ValueError(f"project directory does not exist: {project}")
    state = project / ".synaptory" / ".orchestrator" / "pipeline-state.json"
    if not state.is_file():
        raise ValueError(f"existing Synaptory pipeline state is required: {state}")
    try:
        payload = json.loads(state.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"pipeline state is not valid JSON: {exc.msg}") from exc
    if not isinstance(payload, dict):
        raise ValueError("pipeline state must contain a JSON object")
    return project


def _action(path: Path, kind: str, status: str) -> dict[str, str]:
    return {"path": str(path), "kind": kind, "status": status}


def _prepare(project: Path) -> tuple[dict[str, Any], list[tuple[Path, str]]]:
    actions: list[dict[str, str]] = []
    conflicts: list[dict[str, str]] = []
    writes: list[tuple[Path, str]] = []
    codex_dir = project / ".codex"
    agents_dir = codex_dir / "agents"

    agent_parent_safe = True
    for path in (codex_dir, agents_dir):
        if path.is_symlink():
            agent_parent_safe = False
            conflicts.append(
                {
                    "path": str(path),
                    "reason": "bootstrap directory may not be a symlink",
                }
            )
        elif path.exists() and not path.is_dir():
            agent_parent_safe = False
            conflicts.append(
                {
                    "path": str(path),
                    "reason": "bootstrap directory path is not a directory",
                }
            )

    if agent_parent_safe:
        config_path = codex_dir / "config.toml"
        if config_path.is_symlink():
            conflicts.append(
                {
                    "path": str(config_path),
                    "reason": "Codex project config may not be a symlink",
                }
            )
        elif config_path.exists() and not config_path.is_file():
            conflicts.append(
                {
                    "path": str(config_path),
                    "reason": "Codex project config path is not a file",
                }
            )
        else:
            existing_config = (
                config_path.read_text(encoding="utf-8")
                if config_path.exists()
                else None
            )
            try:
                desired_config, config_status = _codex_config(existing_config)
            except ValueError as exc:
                conflicts.append(
                    {
                        "path": str(config_path),
                        "reason": f"Codex config cannot be modified safely: {exc}",
                    }
                )
            else:
                if config_status == "conflict":
                    conflicts.append(
                        {
                            "path": str(config_path),
                            "reason": (
                                "multi_agent_v2 is explicitly false; Synaptory will not "
                                "override the user's Codex feature choice"
                            ),
                        }
                    )
                else:
                    actions.append(_action(config_path, "codex-feature", config_status))
                    if config_status != "unchanged":
                        writes.append((config_path, desired_config))

        for role in MANAGED_ROLES:
            destination = agents_dir / f"synaptory-{role}.toml"
            desired = _read_template(role)
            if destination.is_symlink():
                conflicts.append(
                    {
                        "path": str(destination),
                        "reason": "managed agent file may not be a symlink",
                    }
                )
                continue
            if destination.exists() and not destination.is_file():
                conflicts.append(
                    {
                        "path": str(destination),
                        "reason": "managed agent path is not a file",
                    }
                )
                continue
            if not destination.exists():
                status = "create"
            else:
                existing = destination.read_text(encoding="utf-8")
                if not existing.startswith(OWNERSHIP_HEADER + "\n"):
                    conflicts.append(
                        {
                            "path": str(destination),
                            "reason": "existing file is not owned by the Synaptory bootstrap",
                        }
                    )
                    continue
                status = "unchanged" if existing == desired else "update"
            actions.append(_action(destination, "agent-profile", status))
            if status != "unchanged":
                writes.append((destination, desired))

    agents_md = project / "AGENTS.md"
    block = _agents_block()
    if agents_md.is_symlink():
        conflicts.append(
            {"path": str(agents_md), "reason": "AGENTS.md may not be a symlink"}
        )
    elif agents_md.exists() and not agents_md.is_file():
        conflicts.append(
            {"path": str(agents_md), "reason": "AGENTS.md path is not a file"}
        )
    else:
        existing = agents_md.read_text(encoding="utf-8") if agents_md.exists() else ""
        starts = existing.count(AGENTS_START)
        ends = existing.count(AGENTS_END)
        if starts == 0 and ends == 0:
            if existing:
                separator = (
                    ""
                    if existing.endswith("\n\n")
                    else ("\n" if existing.endswith("\n") else "\n\n")
                )
                desired = existing + separator + block + "\n"
            else:
                desired = block + "\n"
            status = "create" if not agents_md.exists() else "update"
        elif starts == 1 and ends == 1:
            start = existing.index(AGENTS_START)
            end_start = existing.index(AGENTS_END)
            if end_start < start:
                conflicts.append(
                    {
                        "path": str(agents_md),
                        "reason": "Synaptory AGENTS.md markers are in the wrong order",
                    }
                )
                desired = existing
                status = "conflict"
            else:
                end = end_start + len(AGENTS_END)
                desired = existing[:start] + block + existing[end:]
                status = "unchanged" if existing == desired else "update"
        else:
            conflicts.append(
                {
                    "path": str(agents_md),
                    "reason": "Synaptory AGENTS.md markers are missing, duplicated, or unbalanced",
                }
            )
            desired = existing
            status = "conflict"
        if status != "conflict":
            actions.append(_action(agents_md, "agents-instructions", status))
            if status != "unchanged":
                writes.append((agents_md, desired))

    return (
        {
            "project_dir": str(project),
            "roles": list(MANAGED_ROLES),
            "actions": actions,
            "conflicts": conflicts,
            "apply_allowed": not conflicts,
        },
        writes,
    )


def plan_project(project_dir: str | os.PathLike[str] | Path) -> dict[str, Any]:
    """Return the bootstrap plan without writing project files."""

    project = _project_path(project_dir)
    plan, _writes = _prepare(project)
    return {**plan, "applied": False, "written": []}


def _atomic_write(path: Path, content: str) -> None:
    if path.is_symlink() or path.parent.is_symlink() or path.parent.parent.is_symlink():
        raise ValueError(f"refusing to write through a symlink: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, path.stat().st_mode & 0o777 if path.exists() else 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def bootstrap_project(
    project_dir: str | os.PathLike[str] | Path, *, apply: bool = False
) -> dict[str, Any]:
    """Plan the bootstrap, or apply it when explicitly requested."""

    project = _project_path(project_dir)
    plan, writes = _prepare(project)
    if not apply:
        return {**plan, "applied": False, "written": []}
    if plan["conflicts"]:
        paths = ", ".join(conflict["path"] for conflict in plan["conflicts"])
        raise ValueError(f"bootstrap conflicts must be resolved before apply: {paths}")
    written: list[str] = []
    for path, content in writes:
        _atomic_write(path, content)
        written.append(str(path))
    return {**plan, "applied": True, "written": written}


def inspect_bootstrap(project_dir: str | os.PathLike[str] | Path) -> dict[str, Any]:
    """Inspect whether all profiles and the managed AGENTS.md block are valid."""

    project = Path(project_dir).expanduser().resolve()
    profiles: dict[str, bool] = {}
    for role in MANAGED_ROLES:
        path = project / ".codex" / "agents" / f"synaptory-{role}.toml"
        valid = False
        if path.is_file() and not path.is_symlink():
            try:
                text = path.read_text(encoding="utf-8")
                valid = text == _read_template(role)
            except (OSError, ValueError):
                valid = False
        profiles[role] = valid
    agents_md = project / "AGENTS.md"
    instructions = False
    if agents_md.is_file() and not agents_md.is_symlink():
        try:
            text = agents_md.read_text(encoding="utf-8")
            if text.count(AGENTS_START) == 1 and text.count(AGENTS_END) == 1:
                start = text.index(AGENTS_START)
                end_start = text.index(AGENTS_END)
                if end_start >= start:
                    end = end_start + len(AGENTS_END)
                    instructions = text[start:end] == _agents_block()
        except OSError:
            instructions = False
    config = project / ".codex" / "config.toml"
    multi_agent_v2_configured = False
    if config.is_file() and not config.is_symlink():
        try:
            multi_agent_v2_configured = _multi_agent_v2_value(
                config.read_text(encoding="utf-8")
            ) is True
        except (OSError, ValueError):
            multi_agent_v2_configured = False
    return {
        "installed": all(profiles.values()) and instructions,
        "profiles": profiles,
        "agents_instructions": instructions,
        "multi_agent_v2_configured": multi_agent_v2_configured,
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project_dir", type=Path)
    parser.add_argument(
        "--apply",
        action="store_true",
        help="write managed profiles and AGENTS.md block",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        result = bootstrap_project(args.project_dir, apply=args.apply)
    except (OSError, ValueError) as exc:
        print(json.dumps({"error": str(exc)}))
        return 1
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
