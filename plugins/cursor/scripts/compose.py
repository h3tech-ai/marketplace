def _directives():
    """The shared directive expander from core/scripts (loaded once)."""
    global _DIRECTIVES
    if _DIRECTIVES is None:
        import importlib.util

        path = repo_root() / "core" / "scripts" / "compose_directives.py"
        spec = importlib.util.spec_from_file_location("compose_directives", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _DIRECTIVES = module
    return _DIRECTIVES


