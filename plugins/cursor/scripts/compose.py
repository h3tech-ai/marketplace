_DIRECTIVES = None


def _directives():
    """The shared directive expander from core/scripts (loaded once)."""
    global _DIRECTIVES
    if _DIRECTIVES is None:
        import importlib.util

        path = repo_root() / "core" / "scripts" / "compose_directives.py"
        spec = importlib.util.spec_from_file_location("compose_directives", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _DIRECTIVES = module
    return _DIRECTIVES


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def read_version(root: Path) -> str:
    return (root / "VERSION").read_text(encoding="utf-8").strip()


def with_generated_header(text: str, path: Path) -> str:
    """Insert GENERATED marker; keep shebang first when present."""
    stripped = text
    for marker in (GENERATED_PY, GENERATED_MD):
        stripped = stripped.replace(marker, "")
    ext = path.suffix.lower()
    if ext in {".py", ".sh"}:
        header = GENERATED_PY
    elif ext in {".md", ".mdc", ".json"}:
        header = GENERATED_MD if ext != ".json" else None
    else:
        header = None
    if header is None:
        return stripped
    if ext == ".json":
        return stripped  # JSON cannot take a comment header
    lines = stripped.splitlines(keepends=True)
    if not lines:
        return header
    if lines[0].startswith("#!"):
        i = 1
        if i < len(lines) and "coding" in lines[i]:
            i = 2
        return "".join(lines[:i]) + header + "".join(lines[i:])
    if ext in {".md", ".mdc"} and lines[0].startswith("---"):
        # Frontmatter first, marker immediately after the closing ---
        end = None
        for i, line in enumerate(lines[1:], start=1):
            if line.strip() == "---":
                end = i
                break
        if end is not None:
            return "".join(lines[: end + 1]) + header + "".join(lines[end + 1 :])
    return header + stripped


def copy_text(src: Path, dst: Path, rewrite=None) -> None:
    text = src.read_text(encoding="utf-8")
    if rewrite is not None:
        text = rewrite(text)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(with_generated_header(text, dst), encoding="utf-8")
    # Text rewrite drops the execute bit. Cursor hooks invoke
    # `_resolve-cli.sh` (and siblings) as programs, so they must stay +x.
    #
    # Only chmod when a bit is actually MISSING. `chmod(2)` requires ownership,
    # not write permission, so an unconditional call fails with EPERM wherever
    # the builder can write a file it does not own -- which is exactly the
    # release runner: `release.yml` chowns the workspace to `ghrunner` and makes
    # it `a+w`, then runs the build as `synap`. Every tracked `.sh` is already
    # mode 100755, so after `chmod -R a+w` the exec bits are present and this
    # call was a no-op that could only fail. It broke the 1.2.0 release at the
    # `plugin-cursor compose` step, after a clean build, with nothing published.
    if os.access(src, os.X_OK) or src.suffix == ".sh":
        mode = dst.stat().st_mode
        wanted = mode | 0o111
        if wanted != mode:
            try:
                dst.chmod(wanted)
            except PermissionError as exc:
                raise PermissionError(
                    "cannot make %s executable: %s. The composed hook is "
                    "invoked as a program, so a non-executable copy is a real "
                    "failure -- but check ownership first: chmod needs the file "
                    "to be OWNED by the builder, not merely writable by it."
                    % (dst, exc)
                ) from exc


def rewrite_cursor_host(text: str) -> str:
    """Swap Claude host names in CODE and manifests. Applies to every text file.

    Two things survive here, and neither is a regex over prose:

    * `CLAUDE_PLUGIN_ROOT` is an ENVIRONMENT VARIABLE read by shell hooks and
      shared Python. Renaming it in `.sh` / `.py` / `.json` is a variable
      rename, not a translation of instructions -- a directive cannot help a
      bash script. Authored MARKDOWN no longer spells it (#298): it carries
      `{{path:}}` / `{{self:}}`, which map the token AND the installed layout.
    * The plugin manifest filename differs per host.

    Tool names come from `compose_directives.apply_tool_names` so every host
    declares its own dialect in one table instead of a chain of replacements here.
    """
    text = text.replace("${CLAUDE_PLUGIN_ROOT}", "${PLUGIN_ROOT}")
    text = text.replace("CLAUDE_PLUGIN_ROOT", "PLUGIN_ROOT")
    text = _directives().apply_tool_names(text, "cursor")
    text = text.replace(".claude-plugin/plugin.json", ".cursor-plugin/plugin.json")
    return text


def rewrite_cursor_markdown(
    text: str,
    role: str = "",
    source_dir: Path | None = None,
    own_dir: str = "",
) -> str:
    """Expand content directives, then swap host names.

    Directives live only in markdown. Running the expander over Python or JSON
    would trip its own guard on unrelated brace syntax -- JSX `{{ __html: ... }}`
    in a tech-pack sample, or a docstring that mentions the directive by name.

    `own_dir` is the plugin-relative authoring directory that `{{include:}}` and
    `{{self:}}` resolve against; `role` is shorthand for `agents/<role>`. On
    Cursor an absent one raises instead of composing `${PLUGIN_ROOT}/roles//x`,
    which is the hole-in-the-path bug the directives exist to prevent.
    """
    text = _directives().expand(
        text,
        host="cursor",
        role=role,
        own_dir=own_dir,
        source_dir=source_dir,
        strict=True,
    )
    return rewrite_cursor_host(text)


def _copytree_text(
    src: Path, dst: Path, rewrite=None, skip_names=(), markdown_only_rewrite=False
) -> None:
    skipped = set(skip_names)
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    for root, dirs, files in os.walk(src):
        dirs[:] = [
            d for d in dirs if d not in {".git", "__pycache__"} and d not in skipped
        ]
        rel = Path(root).relative_to(src)
        target_dir = dst / rel
        target_dir.mkdir(parents=True, exist_ok=True)
        for name in files:
            if name in skipped or name.endswith((".pyc", ".pyo")):
                continue
            s = Path(root) / name
            d = target_dir / name
            file_rewrite = rewrite
            if markdown_only_rewrite and s.suffix.lower() != ".md":
                file_rewrite = rewrite_cursor_host
            if name in HOST_NEUTRAL_FILES:
                file_rewrite = None
            if s.suffix.lower() in {".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico"}:
                shutil.copy2(s, d)
            else:
                try:
                    copy_text(s, d, rewrite=file_rewrite)
                except UnicodeDecodeError:
                    shutil.copy2(s, d)


def _patch_plugin_env(text: str) -> str:
    """Look at Cursor plugin.json first for version stamping."""
    text = rewrite_cursor_host(text)
    if ".cursor-plugin/plugin.json" not in text:
        text = text.replace(
            '_plugin_json="${_root}/.claude-plugin/plugin.json"',
            '_plugin_json="${_root}/.cursor-plugin/plugin.json"\n'
            '  if [[ ! -r "$_plugin_json" ]]; then\n'
            '    _plugin_json="${_root}/.claude-plugin/plugin.json"\n'
            "  fi",
        )
    return text


def _stamp_plugin_json(path: Path, version: str) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    data["version"] = version
    if "cli_min_version" in data:
        data["cli_min_version"] = version
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def _split_frontmatter(text: str) -> tuple[str, str]:
    if not text.startswith("---"):
        return "", text
    lines = text.splitlines(keepends=True)
    end = None
    for i, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            end = i
            break
    if end is None:
        return "", text
    return "".join(lines[: end + 1]), "".join(lines[end + 1 :])


def orchestrator_stub(frontmatter: str) -> str:
    """Public-tree stub. Cursor does not expand Claude !bash; first action is Shell."""
    fm = frontmatter.rstrip() + "\n" if frontmatter.strip() else ""
    return (
        f"{fm}\n"
        "# synaptory\n\n"
        "Cursor does not expand Claude `` !`bash` `` stubs. **First action:** "
        "run this with the Shell tool, then follow the printed body exactly. "
        "Do not paste it into the user transcript.\n\n"
        "```bash\n"
        "export SYNAPTORY_IDE=cursor\n"
        "if ! command -v synaptory >/dev/null 2>&1; then\n"
        '  echo "Install the CLI: curl -fsSL https://synaptory.h3t.co/cli/install.sh | bash && synaptory login" >&2\n'
        "  exit 1\n"
        "fi\n"
        "synaptory skills get synaptory --host cursor\n"
        "```\n\n"
        "Do not continue a delivery loop without that body.\n"
    )


