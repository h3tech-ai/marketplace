def generate_agent_md(
    plugin: Path,
    dest_agents: Path,
    version: str,
) -> None:
    dest_agents.mkdir(parents=True, exist_ok=True)
    for role in ROSTER:
        agent_md = plugin / "agents" / role / "agent.md"
        desc = _parse_frontmatter_description(agent_md) if agent_md.is_file() else role
        body = _first_action_body(agent_md, role) if agent_md.is_file() else ""
        fm = {
            "name": role,
            "description": desc,
            "model": "inherit",
        }
        if role in READONLY_AGENTS:
            fm["readonly"] = True
        lines = ["---"]
        for k, v in fm.items():
            if isinstance(v, bool):
                lines.append(f"{k}: {'true' if v else 'false'}")
            elif k == "description":
                lines.append("description: >")
                lines.append(f"  {v}")
            else:
                lines.append(f"{k}: {v}")
        lines.append("---")
        parts = [
            "\n".join(lines),
            GENERATED_MD.rstrip(),
            f"<!-- synaptory compose host=cursor wrapper_version={version} -->",
            body,
            "## Protected bodies",
            "Protocols are **not** inlined here (ADR-016). Cursor cloud agents "
            "do not run sessionStart, so **first action** (required) is this Shell:",
            "```bash\n"
            "export SYNAPTORY_IDE=cursor\n"
            "mkdir -p .synaptory/.protocols\n"
            "for n in "
            + " ".join(_PROTOCOL_FETCH_NAMES)
            + "; do\n"
            "  synaptory skills get \"protocols/$n\" --host cursor "
            "> \".synaptory/.protocols/${n}.md\" || exit 1\n"
            "  test -s \".synaptory/.protocols/${n}.md\" || exit 1\n"
            "done\n"
            "```",
            "Then Read `.synaptory/.protocols/receipt-protocol.md` and the other "
            "protocol files listed in the role SKILL.md. Paths must be exact — "
            "no `2>/dev/null` in the filename. Do not continue if any fetch fails.",
            f"After those reads, follow `${{PLUGIN_ROOT}}/roles/{role}/SKILL.md`.",
            _receipt_block(role),
        ]
        write_text_atomic(
            dest_agents / f"{role}.md",
            "\n\n".join(parts) + "\n",
            mode=0o644,
        )


def compose(src_plugin: Path, dest: Path, version: str, core: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    overlay_hook_py = dest / "hooks" / "lib" / "cursor_hook.py"
    overlay_py_text = overlay_hook_py.read_text(encoding="utf-8") if overlay_hook_py.is_file() else None

    # --- hooks/lib (shared Python, sourced from core/ not from a sibling host) ---
    lib_src = core / "lib"
    lib_dst = dest / "hooks" / "lib"
    keep_overlay = overlay_py_text
    # `cursor_hook.py` is authored here, not composed, so the mirror must leave
    # it alone rather than delete it and have us write it back: this directory is
    # imported by concurrent suites (#568 mechanism 2) and a delete/rewrite pair
    # is a window in which the overlay module does not exist.
    _copytree_text(
        lib_src,
        lib_dst,
        rewrite=rewrite_cursor_host,
        skip_names=("cp-url.local",),
        keep_names=("cursor_hook.py",),
    )
    if keep_overlay is not None and not overlay_hook_py.is_file():
        # Safety net only. `keep_names` above means the mirror never removes it,
        # so the normal path leaves the authored file completely untouched --
        # same inode, same mtime -- rather than destroying and re-creating it.
        write_text_atomic(overlay_hook_py, keep_overlay, mode=0o644)

    # Default CP URL for the committed tree (Team marketplace IS this git
    # folder). Local testing writes gitignored hooks/lib/cp-url.local via
    # `./synaptory deploy local` — do not honour runtime URL env vars.
    write_text_atomic(lib_dst / "cp-url", DEFAULT_CP_URL + "\n", mode=0o644)

    # --- Claude hook scripts (adapters wrap these) ---
    for sh in (src_plugin / "hooks").glob("*.sh"):
        if sh.name in DROP_HOOKS:
            continue
        rewrite = _patch_plugin_env if sh.name == "_plugin-env.sh" else rewrite_cursor_host
        copy_text(sh, dest / "hooks" / sh.name, rewrite=rewrite)
    for extra in ("_plugin-env.sh", "_resolve-cli.sh", "_cp-url.sh"):
        src = src_plugin / "hooks" / extra
        if src.is_file():
            rewrite = _patch_plugin_env if extra == "_plugin-env.sh" else rewrite_cursor_host
            copy_text(src, dest / "hooks" / extra, rewrite=rewrite)

    # --- receipt schema (evidence contract) ---
    # Without this Cursor silently fell back to evidence_contract.EMBEDDED_DEFAULTS
    # while Codex shipped the real JSON, so the two hosts could disagree about the
    # receipt contract they were enforcing.
    schema_src = core / "receipt-schema"
    if schema_src.is_dir():
        _copytree_text(schema_src, dest / "receipt-schema", rewrite=rewrite_cursor_host)

    # --- certified adapter-profile table ---
    # `runtime_selector` resolves this relative to its OWN module, which sits
    # at hooks/lib here, so the table lands beside it rather than at the top of
    # the package. Without it the packaged selector loaded zero profiles and
    # denied every governed dispatch with `no-eligible-profile`, which reads as
    # a policy problem when it is a packaging one (#396).
    fixtures_src = core / "runtime-fixtures"
    if fixtures_src.is_dir():
        _copytree_text(
            fixtures_src,
            dest / "hooks" / "runtime-fixtures",
            rewrite=rewrite_cursor_host,
        )

    # --- shared scripts (tracker, reports, etc.) — not protocols/templates ---
    scripts_src = core / "scripts"
    if scripts_src.is_dir():
        _copytree_text(
            scripts_src,
            dest / "skills" / "_shared" / "scripts",
            rewrite=rewrite_cursor_host,
        )

    # --- orchestrator siblings composed from plugin ---
    skill_src = src_plugin / "skills" / "synaptory"
    skill_dst = dest / "skills" / "synaptory"
    skill_dst.mkdir(parents=True, exist_ok=True)
    for name in ("modes", "ceremonies", "spq"):
        src = skill_src / name
        if src.is_dir():
            # `own_dir` is plugin-relative, and these bodies live under
            # skills/synaptory/<name>/ once installed.
            own = "skills/synaptory/%s" % name
            _copytree_text(
                src,
                skill_dst / name,
                rewrite=lambda text, _own=own, _src=src: rewrite_cursor_markdown(
                    text, own_dir=_own, source_dir=_src
                ),
                markdown_only_rewrite=True,
            )
    routing = skill_src / "routing-rules.json"
    if routing.is_file():
        copy_text(routing, skill_dst / "routing-rules.json")

    # --- role bodies (not scanned as Cursor agents; those are agents/*.md) ---
    # Same reason as `_copytree_text`: no blanket rmtree of a directory another
    # process may be reading. Each role is mirrored in place and roles that left
    # the ROSTER are pruned afterwards (#568 mechanism 2).
    roles_dst = dest / "roles"
    roles_dst.mkdir(parents=True, exist_ok=True)
    for role in ROSTER:
        src = src_plugin / "agents" / role
        if not src.is_dir():
            continue
        _copytree_text(
            src,
            roles_dst / role,
            rewrite=lambda text, _role=role, _src=src: rewrite_cursor_markdown(
                text, role=_role, source_dir=_src
            ),
            markdown_only_rewrite=True,
        )
    for stale in sorted(roles_dst.iterdir()):
        if stale.is_dir() and stale.name not in ROSTER:
            shutil.rmtree(stale)

    generate_agent_md(src_plugin, dest / "agents", version)

    # Drop Claude-only leftover dirs if a previous compose copied them.
    for parts in PURGE_AFTER_BAKE:
        target = dest.joinpath(*parts)
        if target.exists():
            shutil.rmtree(target)

    # Stamp version into overlay plugin.json (file is authored; version is not).
    plugin_json = dest / ".cursor-plugin" / "plugin.json"
    if plugin_json.is_file():
        _stamp_plugin_json(plugin_json, version)

    write_text_atomic(dest / "VERSION", version + "\n", mode=0o644)

    print(f"composed plugin-cursor → {dest} (v{version})", file=sys.stderr)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Destination tree (default: <repo>/plugin-cursor)",
    )
    parser.add_argument(
        "--plugin",
        type=Path,
        default=None,
        help="Source Claude plugin tree (default: <repo>/plugin)",
    )
    parser.add_argument(
        "--strip-ip",
        action="store_true",
        help="Replace orchestrator SKILL.md and overlay docs with CP-fetch stubs. "
        "Use on a marketplace copy, not the private working tree.",
    )
    args = parser.parse_args()
    root = repo_root()
    src = args.plugin or (root / "plugin-claude")
    dest = args.out or (root / "plugin-cursor")
    if args.strip_ip:
        if not dest.is_dir():
            print(f"strip-ip dest not found: {dest}", file=sys.stderr)
            return 2
        strip_marketplace_tree(dest)
        print(f"stripped IP bodies → {dest}", file=sys.stderr)
        return 0
    if not src.is_dir():
        print(f"source plugin not found: {src}", file=sys.stderr)
        return 2
    core = root / "core"
    if not core.is_dir():
        print(f"core runtime not found: {core}", file=sys.stderr)
        return 2
    version = read_version(root)
    compose(src, dest, version, core)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
