def strip_marketplace_tree(dest: Path) -> None:
    """Replace IP-bearing overlay files with CP-fetch stubs (ADR-016 analogue).

    Call on a *copy* destined for a public marketplace. The private
    plugin-cursor working tree keeps full SKILL.md for seed + source-tree dev.
    """
    skill = dest / "skills" / "synaptory" / "SKILL.md"
    if skill.is_file():
        fm, _ = _split_frontmatter(skill.read_text(encoding="utf-8"))
        skill.write_text(orchestrator_stub(fm), encoding="utf-8")
    for rel, name in (
        ("skills/synaptory/dispatch.md", "synaptory/dispatch"),
        ("skills/synaptory/limitations.md", "synaptory/limitations"),
        ("skills/synaptory/receipts.md", "synaptory/receipts"),
    ):
        path = dest / rel
        if path.is_file():
            path.write_text(overlay_doc_stub(name), encoding="utf-8")
    compacted = dest / "hooks" / "lib" / "compacted-rules.md"
    if compacted.is_file():
        compacted.unlink()


def _parse_frontmatter_description(agent_md: Path) -> str:
    text = agent_md.read_text(encoding="utf-8")
    m = re.search(r"^description:\s*>?\s*(.+?)(?=\n(?:model|tools|disallowedTools|color|---):|\n---)", text, re.S | re.M)
    if not m:
        m = re.search(r"^description:\s*(.+)$", text, re.M)
        return (m.group(1).strip() if m else agent_md.stem).strip()
    desc = m.group(1).strip()
    desc = re.sub(r"\s+", " ", desc)
    return desc


def _first_action_body(agent_md: Path, role: str) -> str:
    """The dispatch stub Cursor scans, taken from the authored agent.md body.

    `rewrite_cursor_markdown` handles the `agents/<role>/` -> `roles/<role>/`
    remap now, because `{{path:}}` carries the plugin-relative path and the
    composer owns the layout. The `${PLUGIN_ROOT}/agents/` string patch this
    replaced only ever fixed the stubs; the role SKILL.md bodies kept the
    Claude layout and shipped 15 paths naming a directory Cursor does not have.
    """
    text = agent_md.read_text(encoding="utf-8")
    parts = text.split("\n---\n", 1)
    body = parts[1] if len(parts) > 1 else text
    return rewrite_cursor_markdown(
        body, role=role, source_dir=agent_md.parent
    ).strip()


