# The `!cat` rewriter, the decrypt-line rewriter and their protocol-path helper
# are gone (#298). Authored markdown now carries `{{include:}}` / `{{read:}}` /
# `{{path:}}` / `{{self:}}`, which core/scripts/compose_directives.py expands to
# each host's native form. Nothing here matches prose any more, so a spelling an
# author did not anticipate fails the build instead of shipping untranslated.

# The shared expander is host-neutral BY DESIGN and must reach the Cursor
# package unrewritten. Running the host-token swap over it turned its Claude
# rules into Cursor rules -- its Claude include form returned
# `${PLUGIN_ROOT}/roles/%s` in the composed copy, and its docstring described
# the bug it exists to prevent as "`${PLUGIN_ROOT}/roles` was rewritten to
# `${PLUGIN_ROOT}/roles`".
